// Reads every painted item icon (public/images/items/<id>.webp) and writes the colours the hero's 3D model wears for it
// (src/game/data/itemPalette.ts): the icon's main colour and its accent. Run: node tools/item-palette.mjs
import { readdirSync, writeFileSync } from 'node:fs'
import sharp from 'sharp'

const DIR = 'public/images/items/'
const hsv = (r, g, b) => {
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn
  let h = 0
  if (d) h = mx === r ? ((g - b) / d + 6) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4
  return [h * 60, mx ? d / mx : 0, mx / 255]
}
const hex = ([r, g, b]) => '#' + [r, g, b].map(v => Math.round(v).toString(16).padStart(2, '0')).join('')
const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2])

const out = {}
for (const f of readdirSync(DIR).filter(n => n.endsWith('.webp')).sort()) {
  const { data, info } = await sharp(DIR + f).resize(48, 48, { fit: 'inside' }).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  // 4x4x4 buckets of the opaque, not-ink pixels; saturated pixels count double (a grey outline is not the item's colour).
  const buckets = new Map()
  for (let i = 0; i < data.length; i += info.channels) {
    const [r, g, b, a] = [data[i], data[i + 1], data[i + 2], data[i + 3]]
    if (a < 200) continue
    const [, s, v] = hsv(r, g, b)
    if (v < 0.22) continue
    const k = (r >> 6) * 16 + (g >> 6) * 4 + (b >> 6)
    const e = buckets.get(k) ?? { n: 0, r: 0, g: 0, b: 0 }
    const w = 1 + s * 2
    e.n += w; e.r += r * w; e.g += g * w; e.b += b * w
    buckets.set(k, e)
  }
  const list = [...buckets.values()].map(e => ({ n: e.n, c: [e.r / e.n, e.g / e.n, e.b / e.n] })).sort((a, b) => b.n - a.n)
  if (!list.length) continue
  const main = list[0].c
  const accent = (list.find(e => dist(e.c, main) > 70 && e.n > list[0].n * 0.12) ?? list[1] ?? list[0]).c
  out[f.replace('.webp', '')] = [hex(main), hex(accent)]
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: ['${v[0]}', '${v[1]}']`).join(',\n')
writeFileSync('src/game/data/itemPalette.ts', `// GENERATED by tools/item-palette.mjs from the painted item icons: [main colour, accent] per item id. Do not edit by hand.
/** What the hero's 3D model wears for an item: its icon's main colour and its accent. */
export const ITEM_PALETTE: Readonly<Record<string, readonly [string, string]>> = {
${body}
}
`)
