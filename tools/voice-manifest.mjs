#!/usr/bin/env node
/**
 * The voice manifest: every spoken line of the game, for recording.
 *
 *   pnpm voice:manifest            # write data/voice-manifest.json
 *   pnpm voice:manifest --check    # exit 1 if the file on disk is out of date
 *   pnpm voice:manifest --status   # which recordings exist, per language
 *
 * One entry per dialogue line: its id (which is also its i18n key and the name
 * of its audio file), who says it (the hero, the storyteller, or a person
 * such as `sunfordSmith` or `goblinKing`), their name and look, the tone, the English
 * text, and the file the game plays when it exists:
 *
 *   public/audio/voice/<lang>/<id>.ogg
 *
 * Drop a recording there and the bubble speaks it (`src/game/audio/speech.ts`);
 * nothing else changes. A language without a recording falls back to English.
 * This tool only LISTS the lines. It generates no audio.
 *
 * Reads the game's own data (`src/game/data/dialogs`) and English locale, so
 * it cannot drift from what the game speaks; a test holds the file to it.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import en from '@/i18n/locales/en'
import { SPOKEN } from '@/game/data/dialogs/index'
import { dialogLines } from '@/game/dialog/manifest'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'data', 'voice-manifest.json')
const VOICE = join(root, 'public', 'audio', 'voice')

const text = (key) => {
  let cur = en
  for (const part of key.split('.')) cur = cur && typeof cur === 'object' ? cur[part] : undefined
  return typeof cur === 'string' ? cur : ''
}

// The girl hero (roadmap #71): her own take of every line the hero speaks
// (speaker `heroine`), and a take of any line whose English has a feminine
// variant, each under its own id `<id>__f` (see `feminineTakes`).
const heroic = (s) => s === 'hero' || s === 'heroine'
const lines = dialogLines(SPOKEN, text).map(l => ({
  id: l.id,
  speaker: l.speaker,
  // Who it is, in words (the person ADDRESSED, for a line of the hero's).
  who: l.speaker === 'hero' ? 'The hero' : l.speaker === 'heroine' ? 'The girl hero' : l.speaker === 'narrator' ? 'The storyteller' : text(l.name),
  ...(l.look && l.look !== l.speaker ? { look: l.look } : {}),
  scene: l.scene,
  ...(heroic(l.speaker) && l.name ? { to: text(l.name) } : {}),
  emotion: l.emotion,
  ...(l.gesture ? { gesture: l.gesture } : {}),
  text: l.text,
  file: l.file,
  ...(l.variantOf ? { variantOf: l.variantOf } : {})
}))

const speakers = {}
for (const l of lines) speakers[l.speaker] = (speakers[l.speaker] ?? 0) + 1

const manifest = {
  note: 'Generated by `pnpm voice:manifest` from src/game/data/dialogs and the English locale. Do not edit by hand.',
  language: 'en',
  path: 'public/audio/voice/<lang>/<id>.ogg',
  count: lines.length,
  speakers,
  lines
}
const json = `${JSON.stringify(manifest, null, 2)}\n`

const empty = lines.filter(l => !l.text)
if (empty.length) {
  console.error(`voice-manifest: ${empty.length} line(s) have no English text:\n  ${empty.map(l => l.id).join('\n  ')}`)
  process.exit(1)
}

if (process.argv.includes('--status')) {
  const ids = new Set(lines.map(l => l.id))
  if (!existsSync(VOICE)) console.log(`no recordings yet (${VOICE} does not exist); ${lines.length} lines are text-paced`)
  else {
    for (const lang of readdirSync(VOICE, { withFileTypes: true }).filter(d => d.isDirectory())) {
      const files = readdirSync(join(VOICE, lang.name)).map(f => f.slice(0, f.lastIndexOf('.')))
      const have = files.filter(f => ids.has(f))
      const stray = files.filter(f => !ids.has(f))
      console.log(`${lang.name}: ${have.length} / ${lines.length} lines recorded${stray.length ? `, ${stray.length} file(s) match no line: ${stray.slice(0, 5).join(', ')}` : ''}`)
    }
  }
  process.exit(0)
}

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
  if (cur !== json) {
    console.error('voice-manifest: data/voice-manifest.json is out of date — run `pnpm voice:manifest`')
    process.exit(1)
  }
  console.log(`voice-manifest: up to date (${lines.length} lines)`)
  process.exit(0)
}

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, json)
console.log(`voice-manifest: ${lines.length} lines, ${Object.keys(speakers).length} voices → ${OUT}`)
for (const [s, n] of Object.entries(speakers).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(4)}  ${s}`)
