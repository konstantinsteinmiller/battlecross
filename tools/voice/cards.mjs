// `pnpm voice:cards` — prints the voice cards (src/game/audio/voiceCards.ts)
// as a readable sheet, voice-cards.md: who each speaker is as a voice, what the
// voice-design model is told, the reference text, and how their lines split
// by tone. Change a card in voiceCards.ts, then re-run this.

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { FX_SPEAKERS as FX_SPEAKERS_LIST } from './fx.mjs'
import { CARDS, VOICE_LINES, ROOT } from './lib.mjs'

const rows = []
rows.push(`# Voice cards

Generated by \`pnpm voice:cards\` (tools/voice/cards.mjs) from
\`src/game/audio/voiceCards.ts\`. Do not edit by hand.

Each card is what the voice-design model (Qwen3 VoiceDesign) is told to
create: a clean, natural human voice. Every line is then cloned from one
frozen reference clip per voice (\`vo-src/refs/<voice>/en.qwen.wav\`), read
from the reference text below. Only the creatures get a light effect
afterwards (${FX_SPEAKERS_LIST.join(', ')}: tools/voice/fx.mjs).
`)
for (const [id, c] of Object.entries(CARDS)) {
  const lines = VOICE_LINES.filter(l => l.speaker === id)
  const tones = {}
  for (const l of lines) tones[l.tone] = (tones[l.tone] ?? 0) + 1
  const split = Object.entries(tones).sort((a, b) => b[1] - a[1]).map(([t, n]) => `${t} ${n}`).join(', ')
  rows.push(`## ${c.name} (\`${id}\`)

| Gender | Age | Pitch | Pace | Timbre |
| --- | --- | --- | --- | --- |
| ${c.gender} | ${c.age} | ${c.pitch} | ${c.pace} | ${c.timbre} |

${c.personality}

- **Accent:** ${c.accent.en}
- **Design prompt:** ${c.designPrompt.en}
- **Reference text:** ${c.referenceText.en}
- **Lines:** ${lines.length}${split ? ` (${split})` : ''}
${c.notes ? `- **Notes:** ${c.notes}\n` : ''}`)
}
writeFileSync(join(ROOT, 'voice-cards.md'), rows.join('\n'))
console.log(`voice-cards.md: ${Object.keys(CARDS).length} cards, ${VOICE_LINES.length} lines`)
