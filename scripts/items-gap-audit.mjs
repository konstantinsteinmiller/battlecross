// Writes items-gap-audit.md: the item catalogue as a matrix (attribute line x slot x quality), before
// and after the gap-fill set, with the gaps found, the budget outliers and the drop-table sizes.
//
//   node --import ./tools/ts-resolve.mjs scripts/items-gap-audit.mjs
//
// The "before" catalogue is the found gear without `GAPFILL_ITEMS`; the "after" is all of it.
import { writeFileSync } from 'node:fs'
import { ITEMS, GAPFILL_ITEMS, GEAR_ATTR_SCALE, ITEM_BUDGET } from '../src/game/data/items.ts'
import { ITEM_LINES, MATRIX_SLOTS, MATRIX_TIERS, cellOf, budgetRatio } from '../src/game/data/itemMatrix.ts'
import { ZONE_LOOT } from '../src/game/data/loot.ts'
import { ZONE_IDS } from '../src/game/data/zones.ts'

const BEFORE = ITEMS.filter(i => !GAPFILL_ITEMS.has(i.id))
const AFTER = ITEMS
const LINE_NAME = { str: 'Strength', dex: 'Dexterity', int: 'Intelligence', skl: 'Skill', cha: 'Charisma', end: 'Endurance' }
const SLOT_NAME = { main: 'main hand', off: 'off hand', head: 'head', body: 'body', hands: 'hands', feet: 'feet', trinket: 'trinket' }
const TIER_NAME = { 1: 'Common', 2: 'Uncommon', 3: 'Rare', 4: 'Epic', 5: 'Heroic', 6: 'Legendary' }
const WEAPONS = {
  str: 'swords, greatswords, axes, hammers (the Blade of the Unbound, Ashen Greatsword, Blood-Forged Axe, Dragon Smasher)',
  dex: 'daggers and rapiers (daggers, the Chrono Blade and the Phantom Rapier are swords that scale on DEX)',
  int: 'wands and staves (Apprentice Staff, Archmage Wand)',
  skl: 'pistols, carbines and cannons (`gun`, `cannon`: Scout\'s Handgun to the Aetherium Destroyer)',
  cha: 'sceptres, banners and crooks (`wand`, `staff` that scale on CHA)',
  end: 'maces and axes (`hammer`, `axe` that scale on END; the old catalogue had none, only the forge made them)'
}

const cellsOf = (items) => Object.fromEntries(ITEM_LINES.map(line => [line, Object.fromEntries(MATRIX_SLOTS.map(slot => [slot, MATRIX_TIERS.map(t => cellOf(items, line, slot, t).length)]))]))
const empties = (m) => ITEM_LINES.flatMap(line => MATRIX_SLOTS.flatMap(slot => MATRIX_TIERS.filter(t => m[line][slot][t - 1] === 0).map(t => ({ line, slot, t }))))
const holes = (m) => ITEM_LINES.flatMap(line => MATRIX_SLOTS.flatMap(slot => {
  const row = m[line][slot]
  const lo = row.findIndex(n => n > 0)
  const hi = row.length - 1 - [...row].reverse().findIndex(n => n > 0)
  return lo < 0 ? [] : MATRIX_TIERS.filter(t => t - 1 > lo && t - 1 < hi && row[t - 1] === 0).map(t => ({ line, slot, t }))
}))
const blankSlots = (m) => ITEM_LINES.flatMap(line => MATRIX_SLOTS.filter(slot => m[line][slot].every(n => n === 0)).map(slot => ({ line, slot })))
const table = (m, line) => {
  const head = `| slot | ${MATRIX_TIERS.map(t => `T${t}`).join(' | ')} | pieces |\n|---|${MATRIX_TIERS.map(() => '--:').join('|')}|--:|`
  const rows = MATRIX_SLOTS.map(slot => `| ${SLOT_NAME[slot]} | ${m[line][slot].map(n => (n === 0 ? '**0**' : String(n))).join(' | ')} | ${m[line][slot].reduce((a, b) => a + b, 0)} |`)
  return [head, ...rows].join('\n')
}
const total = (m, line) => MATRIX_SLOTS.reduce((n, s) => n + m[line][s].reduce((a, b) => a + b, 0), 0)
const filled = (m, line) => MATRIX_SLOTS.reduce((n, s) => n + m[line][s].filter(x => x > 0).length, 0)

const B = cellsOf(BEFORE)
const A = cellsOf(AFTER)
const out = []
const w = (s = '') => out.push(s)

w('# Item gap audit')
w()
w('Generated by `scripts/items-gap-audit.mjs` from the game\'s own data (`src/game/data/items.ts`); rerun it after any item change. `tests/game/itemMatrix.test.ts` holds the invariants below.')
w()
w('## Method')
w()
w('- **Catalogue**: the found gear (`ITEMS`), the pieces a hero can drop, buy or win. Forged gear (`SMITHED`, 432 pieces: six builds, six metals, plain and masterwork) and the six colosseum mythics are not in the matrix: they are made or earned, never found, and the forge already covers every build, slot of its six pieces and metal.')
w('- **Attribute line** (a build): strength, dexterity, intelligence, skill, charisma, endurance. A weapon belongs to the attribute its swing scales on. Any other piece **serves** a line when that attribute is at least half of the piece\'s top attribute, so heavy gear that leads with endurance and carries strength counts for both builds; a ring of every attribute serves all.')
w('- **Cell**: one line x one slot (main hand, off hand, head, body, hands, feet, trinket; the hero wears two trinkets) x one quality (T1 Common, T2 Uncommon, T3 Rare, T4 Epic, T5 Heroic, T6 Legendary). The tier bands of GDD 6.2: T1 level 1-5, T2 6-10, T3 11-15, T4 16-20, T5 21-25, T6 26-30 (legendaries are found from hero level 28).')
w('- **Gap** (any of): an empty cell where a sibling line has a piece; a tier hole in a ladder (a line has the Rare and the Heroic piece of a slot but no Epic); a slot a build cannot fill at all; a piece far from the stat budget of its slot and quality (see Balance).')
w()
w('### Weapon types per line (the game\'s real ones)')
w()
for (const l of ITEM_LINES) w(`- **${LINE_NAME[l]}**: ${WEAPONS[l]}`)
w()
w('### Quality ladder: the level ranges of the found gear')
w()
w('| quality | before | after |')
w('|---|---|---|')
for (const t of MATRIX_TIERS) {
  const r = (items) => { const l = items.filter(i => i.tier === t).map(i => i.level); return `${items.filter(i => i.tier === t).length} pieces, level ${Math.min(...l)}-${Math.max(...l)}` }
  w(`| T${t} ${TIER_NAME[t]} | ${r(BEFORE)} | ${r(AFTER)} |`)
}
w()
w('### Budget rules the existing items follow')
w()
w('- A piece carries the attribute points of its slot and quality, **before** the quality\'s share (`GEAR_ATTR_SCALE`: 0.5, 0.4, 0.32, 0.28, 0.25, 0.22). The table below is `ITEM_BUDGET`, the yardstick found in the older pieces (a weapon 6, 23, 41, 61, 88, 141; head, hands and feet 30-45 % of a body armour, GDD D39).')
w('')
w(`| slot | ${MATRIX_TIERS.map(t => `T${t}`).join(' | ')} |`)
w(`|---|${MATRIX_TIERS.map(() => '--:').join('|')}|`)
for (const s of MATRIX_SLOTS) w(`| ${SLOT_NAME[s]} | ${ITEM_BUDGET[s].join(' | ')} |`)
w()
w('- Body armour: a plate carries 14, 28, 55, 85, 140, 220 armour by quality; leather, cloth and robes carry a share of it (skill 0.8, dexterity 0.75, charisma and intelligence 0.6, the forge\'s own factors). Helms, gauntlets and greaves carry their armour as a modifier: head 0.32, hands 0.25, feet 0.29 of a plate.')
w('- Head, hands and feet use only a few small modifiers (D39): move speed, dodge, attack speed, crit, spell crit, crit damage, cooldown reduction, stun resistance, armour, mana.')
w('- Each line\'s own extras (what its skills feed): strength block and boss damage, endurance stun resistance and regeneration, intelligence mana and spell crit, skill attack speed and heat, charisma minion health and damage, dexterity speed, crit and dodge.')
w()

w('## Before')
w()
w('Found pieces counted per line (a hybrid piece counts for every line it serves).')
w()
w(`| line | cells filled (of 42) | empty cells | tier holes | slots it cannot fill |`)
w('|---|--:|--:|--:|--|')
for (const l of ITEM_LINES) {
  const e = empties(B).filter(x => x.line === l).length
  const h = holes(B).filter(x => x.line === l).length
  const bs = blankSlots(B).filter(x => x.line === l).map(x => SLOT_NAME[x.slot]).join(', ') || '-'
  w(`| ${LINE_NAME[l]} | ${filled(B, l)} | ${e} | ${h} | ${bs} |`)
}
w()
w(`Total: ${empties(B).length} empty cells of ${ITEM_LINES.length * 42}, ${holes(B).length} of them holes inside a ladder.`)
w()
for (const l of ITEM_LINES) {
  w(`### ${LINE_NAME[l]} (before)`)
  w()
  w(table(B, l))
  w()
  const e = empties(B).filter(x => x.line === l)
  w(e.length ? `Empty: ${MATRIX_SLOTS.map(s => { const ts = e.filter(x => x.slot === s).map(x => `T${x.t}`); return ts.length ? `${SLOT_NAME[s]} ${ts.join(', ')}` : '' }).filter(Boolean).join('; ')}.` : 'No empty cells.')
  w()
}

w('## The fill')
w()
w(`${GAPFILL_ITEMS.size} new fixed pieces (\`GAPFILL_ITEMS\`), one for every empty cell, each with a distinct name and a painted-icon description of its own, nine icon sheets (\`sheet-items-fill-1\` to \`-9\`). Nothing rolls, each is owned once. Every one drops from the chests and mobs (or, for legendaries, the Dread Fortress's boss and chests) of a zone of its own quality, and is sold by the armourers and weaponsmiths whose stock names its slot and quality, exactly like the older pieces: no shop, gambler or table was edited, they read the catalogue.`)
w()
w('| line | pieces added | T1 | T2 | T3 | T4 | T5 | T6 |')
w('|---|--:|--:|--:|--:|--:|--:|--:|')
const added = ITEMS.filter(i => GAPFILL_ITEMS.has(i.id))
for (const l of ITEM_LINES) {
  const mine = added.filter(i => cellOf([i], l, i.slot, i.tier).length > 0 && (i.weapon ? i.weapon.scale === l : true))
  // a piece is "added for" the line it was made for: the cell it filled was empty before
  const own = mine.filter(i => cellOf(BEFORE, l, i.slot, i.tier).length === 0)
  w(`| ${LINE_NAME[l]} | ${own.length} | ${MATRIX_TIERS.map(t => own.filter(i => i.tier === t).length).join(' | ')} |`)
}
w()
w('(A heavy piece made for strength also serves endurance and the other way round, so the rows add up to more than the number of pieces.)')
w()
w('Legendaries (T6, level 28-30) added, by slot:')
w()
for (const s of MATRIX_SLOTS) {
  const names = added.filter(i => i.slot === s && i.tier === 6)
  if (names.length) w(`- ${SLOT_NAME[s]}: ${names.map(i => `${i.id} (${i.drop.src})`).join(', ')}`)
}
w()

w('## After')
w()
w(`| line | cells filled (of 42) | empty cells | tier holes | slots it cannot fill | pieces |`)
w('|---|--:|--:|--:|--|--:|')
for (const l of ITEM_LINES) w(`| ${LINE_NAME[l]} | ${filled(A, l)} | ${empties(A).filter(x => x.line === l).length} | ${holes(A).filter(x => x.line === l).length} | ${blankSlots(A).filter(x => x.line === l).map(x => SLOT_NAME[x.slot]).join(', ') || '-'} | ${total(A, l)} |`)
w()
w(`Total: ${empties(A).length} empty cells, ${holes(A).length} tier holes, ${blankSlots(A).length} unfillable slots. No cell stays empty: every line has a weapon (of its own kinds), an off hand, head, body, hands, feet and trinket at every quality from Common to Legendary, so a pure build of any line exists from level 1 to 30.`)
w()
for (const l of ITEM_LINES) {
  w(`### ${LINE_NAME[l]} (after)`)
  w()
  w(table(A, l))
  w()
}

w('## Balance')
w()
w('A piece\'s ratio is its attribute points (before the quality\'s share) over the budget of its slot and quality. `tests/game/itemMatrix.test.ts` keeps every found piece within 50 % to 150 % of the budget (a point of rounding either way) and the new ones within a quarter of it.')
w()
const out2 = ITEMS.filter(i => { const r = budgetRatio(i); return r < 0.75 || r > 1.3 }).sort((a, b) => budgetRatio(a) - budgetRatio(b))
w('Pieces outside 75 %-130 % of their budget (rounding at the lowest qualities included):')
w()
w('| piece | slot | quality | ratio | note |')
w('|---|---|---|--:|---|')
const NOTE = {
  paddedTunic: 'the starter\'s body armour: its point is the 8 armour, the opening is tuned on it; left as tabled',
  quiltedCap: 'a Common cap, two attribute points and 4 armour; within the band',
  armorOfTheTitan: 'the GDD\'s top legendary plate (85 STR + 85 END, 220 armour); inside the band',
  ringOfAbsolutePower: 'the secret ring of every attribute (counted as six): the capstone of the tables, the only exemption in the test',
  sovereignsSignet: 'its 20 % minion damage stands in for the points; pinned by the GDD table test',
  tomeOfNovices: 'a Common tome with mana; within the band',
  forgeplateGreaves: 'its stun resistance stands in for the points; within the band',
  hymnalOfTheRoad: 'a Common tome (end, minion health); within the band'
}
for (const i of out2) w(`| ${i.id} | ${SLOT_NAME[i.slot]} | ${TIER_NAME[i.tier]} | ${budgetRatio(i).toFixed(2)} | ${NOTE[i.id] ?? (GAPFILL_ITEMS.has(i.id) ? 'new: a point of rounding at the lowest qualities' : 'older piece: its extras (a passive or a percentage) stand in for points; inside 50-150 %')} |`)
w()
w('Outliers fixed: none of the older pieces was changed. The GDD-tabled numbers (pinned by `tests/game/data.test.ts`, saves and the opening balance) stay as they are; the only piece outside the 50-150 % band is the Ring of Absolute Power, an explicit exemption. The weak spots among the older lines were holes, not outliers, and are filled by pieces on budget.')
w()

w('## Drop tables')
w()
w('Equipment a chest of a zone can hold (`ZONE_LOOT`, mobs and chests), and what a finale boss pays (`boss`). The Void Rift\'s chests hold the Dread Fortress\'s. Chests draw a piece the hero does not own yet first, so a bigger table lengthens the hunt without lowering the first finds.')
w()
w('| zone | chest table before | after | boss drops before | after |')
w('|---|--:|--:|--:|--:|')
for (const z of ZONE_IDS) {
  const after = ZONE_LOOT[z].items
  const before = after.filter(id => !GAPFILL_ITEMS.has(id))
  const bossAfter = ITEMS.filter(i => i.drop.zone === z && i.drop.src === 'boss')
  const bossBefore = bossAfter.filter(i => !GAPFILL_ITEMS.has(i.id))
  w(`| ${z} | ${before.length} | ${after.length} | ${bossBefore.length} | ${bossAfter.length} |`)
}
w()
w('## Decisions and notes')
w()
w('- The strength and endurance lines share their heavy gear (a plate that leads with endurance and carries strength serves both builds, as it always did); only the weapons are split by the attribute the blow scales on. If the owner wants strictly separate lines, the pieces that count for both would each need a twin.')
w('- Endurance now has maces and axes that scale on END in every quality. Before, only the forge made END weapons.')
w('- The new legendaries are boss and chest finds of the Dread Fortress, the same place as the other legendaries. Four of the sixteen are boss drops (its boss table goes from four pieces to eight), the other twelve are chest finds; the Void Rift\'s three boss pieces are unchanged. Owner decision: a hero needs eight Fortress kills to see every boss legendary; say if some should move to the Rift.')
w('- Item icons are procedural until painted: nine sheets (`sheet-items-fill-1` ... `-9`) with prompts in `art-sheets/PROMPTS-ITEMS.md`.')
w()
writeFileSync(new URL('../items-gap-audit.md', import.meta.url), out.join('\n') + '\n')
console.log(`items-gap-audit.md: ${empties(B).length} empty cells before, ${empties(A).length} after`)
